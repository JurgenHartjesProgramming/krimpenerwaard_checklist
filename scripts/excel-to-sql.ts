/**
 * Convert the "Stakeholders per fase" Excel sheet into an SQL import that creates a NEW project.
 * (To convert a project that was imported before activities existed, use template-to-activities.ts.)
 *
 * Usage:
 *   npx tsx scripts/excel-to-sql.ts "<path to .xlsx>" [output.sql] [project name]
 *
 * Mapping (see scripts/lib/phase-sheet.ts for the sheet layout):
 *   - every "Fase" becomes a phase (description = the intro row);
 *   - every step row becomes an activity: number, name, description ("Wat doe/controleer je?"), result;
 *   - the parties in "Leidend" and "Ook betrokken" become the activity's stakeholders with that role.
 * Statuses start at "not started"; contact details, deadlines and interests are empty.
 *
 * The SQL also writes "create" events into history_events, so the import shows up in the project
 * timeline and can be reverted. It refuses to run when a project with the same name exists.
 */
import { randomUUID } from "node:crypto";
import { writeFileSync } from "node:fs";
import { membersOf, readPhaseSheet } from "./lib/phase-sheet";
import { importContext, q, snapshot } from "./lib/sql";

async function main() {
  const [path, output = "import.sql", projectName = "Sjabloon – Stakeholders per fase"] = process.argv.slice(2);
  if (!path) {
    console.error('Usage: npx tsx scripts/excel-to-sql.ts "<file.xlsx>" [output.sql] [project name]');
    process.exit(1);
  }
  const source = path.split(/[\\/]/).pop()!;
  const phases = await readPhaseSheet(path);
  const projectId = randomUUID();
  const out: string[] = [];
  const note = q(`Geïmporteerd uit Excel: ${source}`);
  let activityCount = 0;
  let stakeholderCount = 0;
  let seq = 0;

  const body: string[] = [];
  phases.forEach((p, pi) => {
    const phaseId = randomUUID();
    body.push(`-- Fase ${pi + 1}: ${p.name}`);
    body.push(
      `INSERT INTO phases (id, project_id, name, description, sort_order) VALUES (${q(phaseId)}, ${q(projectId)}, ${q(p.name)}, ${q(p.description)}, ${pi + 1});`,
    );
    p.steps.forEach((s, si) => {
      const activityId = randomUUID();
      activityCount++;
      const at = `now() + ${seq++} * interval '1 millisecond'`;
      body.push(
        `INSERT INTO activities (id, project_id, phase_id, number, name, description, result, sort_order, created_at, updated_at) VALUES (${q(activityId)}, ${q(projectId)}, ${q(phaseId)}, ${q(s.nr)}, ${q(s.title)}, ${q(s.check)}, ${q(s.result)}, ${si + 1}, ${at}, ${at});`,
      );
      const members = membersOf(s);
      if (members.length) {
        body.push(`INSERT INTO stakeholders (project_id, phase_id, activity_id, role, sort_order, name, created_at, updated_at) VALUES`);
        body.push(
          members
            .map(
              (m, mi) =>
                `  (${q(projectId)}, ${q(phaseId)}, ${q(activityId)}, '${m.role}', ${mi + 1}, ${q(m.name)}, ${at} + ${mi} * interval '1 microsecond', ${at})`,
            )
            .join(",\n") + ";",
        );
        stakeholderCount += members.length;
      }
    });
    body.push("");
  });

  out.push(`-- Import: ${source}`);
  out.push(`-- Generated by scripts/excel-to-sql.ts on ${new Date().toISOString()}`);
  out.push(
    `-- Creates project "${projectName}" with ${phases.length} phases, ${activityCount} activities and ${stakeholderCount} stakeholders.`,
  );
  out.push(`-- Stops when a project with this name already exists.`);
  out.push(``);
  out.push(`BEGIN;`);
  out.push(``);
  out.push(`DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM projects WHERE name = ${q(projectName)} AND deleted_at IS NULL) THEN
    RAISE EXCEPTION 'Project "%" bestaat al. Hernoem of verwijder het eerst; er is niets geïmporteerd.', ${q(projectName)};
  END IF;
END $$;`);
  out.push(``);
  out.push(
    `INSERT INTO projects (id, name, description, status) VALUES (${q(projectId)}, ${q(projectName)}, ${q(`Geïmporteerd uit "${source}". Gebruik dit project als bron bij "Kopiëren uit project".`)}, 'active');`,
  );
  out.push(``);
  out.push(...body);
  out.push(`-- Version history: register the import so it appears in the timeline and can be reverted.`);
  out.push(importContext);
  out.push(``);
  for (const [type, table, order] of [
    ["project", "projects", "x.created_at"],
    ["phase", "phases", "x.sort_order"],
    ["activity", "activities", "x.created_at"],
    ["stakeholder", "stakeholders", "x.created_at"],
  ] as const) {
    const projectCol = type === "project" ? "x.id" : "x.project_id";
    out.push(`INSERT INTO history_events (project_id, entity_type, entity_id, op, before, after, actor_id, batch_id, note)
SELECT ${projectCol}, '${type}', x.id, 'create', NULL, ${snapshot[type]("x")}, c.actor_id, c.batch_id, ${note}
FROM ${table} x CROSS JOIN import_ctx c WHERE ${projectCol} = ${q(projectId)} ORDER BY ${order};
`);
  }
  out.push(`COMMIT;`);
  writeFileSync(output, out.join("\n") + "\n", "utf8");

  for (const [i, p] of phases.entries()) {
    const n = p.steps.reduce((sum, s) => sum + membersOf(s).length, 0);
    console.log(`Fase ${i + 1}: ${p.name} — ${p.steps.length} activiteiten, ${n} stakeholderregels`);
  }
  console.log(`SQL written to ${output}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
