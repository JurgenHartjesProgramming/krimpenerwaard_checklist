/**
 * Convert an existing project that was imported from "Stakeholders per fase" (one stakeholder row
 * per party per phase) to the activity model: every step row of the sheet becomes an activity, and
 * the parties in "Leidend" / "Ook betrokken" become that activity's stakeholders.
 *
 * Usage (reads names from DATABASE_URL, read-only, for the report):
 *   npx tsx scripts/template-to-activities.ts "<V01 .xlsx>" [output.sql] [project name]
 *
 * What the generated SQL does, in one transaction:
 *   1. creates the activities (number, name, description = "Wat doe/controleer je?", result);
 *   2. per activity creates a stakeholder row for each party, copying from the existing phase-level
 *      row with the same name: contact details, deadline, status, "Belangen en eisen" (incl. imported
 *      conflicts), plus its documentation links/files and comments. The generated texts from the
 *      first import ("Leidend bij: …" and the per-step to-do list) are dropped: they now live on the
 *      activity itself. A party without an existing row gets a new, empty stakeholder;
 *   3. soft-deletes the old phase-level rows that were converted (revertable via Geschiedenis);
 *   4. writes every change to history_events in one batch.
 * It refuses to run on a project that already has activities.
 */
import "dotenv/config";
import { writeFileSync } from "node:fs";
import postgres from "postgres";
import { membersOf, readPhaseSheet } from "./lib/phase-sheet";
import { importContext, q, snapshot } from "./lib/sql";

async function main() {
  const [path, output = "imports/sjabloon-naar-activiteiten.sql", projectName = "Sjabloon – Stakeholders per fase"] =
    process.argv.slice(2);
  if (!path) {
    console.error('Usage: npx tsx scripts/template-to-activities.ts "<file.xlsx>" [output.sql] [project name]');
    process.exit(1);
  }
  const source = path.split(/[\\/]/).pop()!;
  const phases = await readPhaseSheet(path);

  // Report which parties have an existing row to copy from (read-only).
  const db = postgres(process.env.DATABASE_URL!, { max: 1 });
  const rows = await db`
    select f.name as phase, s.name
    from stakeholders s
    join phases f on f.id = s.phase_id and f.deleted_at is null
    join projects p on p.id = s.project_id and p.deleted_at is null
    where p.name = ${projectName} and s.deleted_at is null and s.activity_id is null`;
  const phaseRows = await db`
    select f.name from phases f join projects p on p.id = f.project_id
    where p.name = ${projectName} and p.deleted_at is null and f.deleted_at is null`;
  await db.end();
  const existing = new Set(rows.map((r) => `${r.phase}|${r.name}`));
  const phaseNames = new Set(phaseRows.map((r) => r.name as string));

  const activityValues: string[] = [];
  const memberValues: string[] = [];
  const missingPhases: string[] = [];
  const newParties: string[] = [];
  let seq = 0;
  for (const p of phases) {
    if (!phaseNames.has(p.name)) missingPhases.push(p.name);
    p.steps.forEach((s, i) => {
      activityValues.push(
        `  (${q(p.name)}, ${i + 1}, ${seq++}, ${q(s.nr)}, ${q(s.title)}, ${q(s.check)}, ${q(s.result)})`,
      );
      membersOf(s).forEach((m, j) => {
        memberValues.push(`  (${q(p.name)}, ${q(s.nr)}, ${q(m.name)}, '${m.role}'::stakeholder_role, ${j + 1})`);
        if (!existing.has(`${p.name}|${m.name}`)) newParties.push(`${s.nr} ${m.name}`);
      });
    });
  }

  const note = q(`Omgezet naar activiteiten (bron: ${source})`);
  const event = (type: string, op: string, alias: string, before = "NULL") =>
    `SELECT ${alias}.project_id, '${type}', ${alias}.id, '${op}', ${before}, ${snapshot[type as keyof typeof snapshot](alias)}, c.actor_id, c.batch_id, ${note}`;

  const sql = `-- Convert project "${projectName}" to activities, using: ${source}
-- Generated by scripts/template-to-activities.ts on ${new Date().toISOString()}
-- ${activityValues.length} activities, ${memberValues.length} stakeholder links.
-- Runs in one transaction; refuses to run if the project already has activities.

BEGIN;

CREATE TEMP TABLE tpl ON COMMIT DROP AS
SELECT id FROM projects WHERE name = ${q(projectName)} AND deleted_at IS NULL;

DO $$
BEGIN
  IF (SELECT count(*) FROM tpl) <> 1 THEN
    RAISE EXCEPTION 'Project "%" niet (of meer dan eens) gevonden. Er is niets aangepast.', ${q(projectName)};
  END IF;
  IF EXISTS (SELECT 1 FROM activities a JOIN tpl ON tpl.id = a.project_id WHERE a.deleted_at IS NULL) THEN
    RAISE EXCEPTION 'Dit project heeft al activiteiten. Er is niets aangepast.';
  END IF;
END $$;

${importContext}

CREATE TEMP TABLE act_import (phase_name text, sort int, seq int, number text, name text, description text, result text) ON COMMIT DROP;
INSERT INTO act_import VALUES
${activityValues.join(",\n")};

CREATE TEMP TABLE member_import (phase_name text, number text, stakeholder_name text, role stakeholder_role, sort int) ON COMMIT DROP;
INSERT INTO member_import VALUES
${memberValues.join(",\n")};

-- 1. Activities
WITH ins AS (
  INSERT INTO activities (project_id, phase_id, number, name, description, result, sort_order, created_at, updated_at)
  SELECT tpl.id, f.id, ai.number, ai.name, ai.description, ai.result, ai.sort,
         now() + ai.seq * interval '1 millisecond', now() + ai.seq * interval '1 millisecond'
  FROM act_import ai
  CROSS JOIN tpl
  JOIN phases f ON f.project_id = tpl.id AND f.name = ai.phase_name AND f.deleted_at IS NULL
  RETURNING *
)
INSERT INTO history_events (project_id, entity_type, entity_id, op, before, after, actor_id, batch_id, note)
${event("activity", "create", "ins")}
FROM ins CROSS JOIN import_ctx c ORDER BY ins.created_at;

DO $$
BEGIN
  IF (SELECT count(*) FROM activities a JOIN tpl ON tpl.id = a.project_id WHERE a.deleted_at IS NULL)
     <> (SELECT count(*) FROM act_import) THEN
    RAISE EXCEPTION 'Niet alle fases uit de Excel bestaan in het project. Er is niets aangepast.';
  END IF;
END $$;

-- 2. One stakeholder row per party per activity, copied from the old phase-level row (if any)
CREATE TEMP TABLE member_map ON COMMIT DROP AS
SELECT gen_random_uuid() AS new_id, src.id AS src_id, a.id AS activity_id, a.phase_id, mi.role, mi.sort,
       mi.stakeholder_name, a.created_at
FROM member_import mi
CROSS JOIN tpl
JOIN phases f ON f.project_id = tpl.id AND f.name = mi.phase_name AND f.deleted_at IS NULL
JOIN activities a ON a.phase_id = f.id AND a.number = mi.number AND a.deleted_at IS NULL
LEFT JOIN LATERAL (
  SELECT s.id FROM stakeholders s
  WHERE s.phase_id = f.id AND s.activity_id IS NULL AND s.deleted_at IS NULL AND s.name = mi.stakeholder_name
  ORDER BY s.sort_order LIMIT 1
) src ON true;

INSERT INTO stakeholders (
  id, project_id, phase_id, activity_id, role, sort_order, name, contact_person, email, phone, description,
  deadline, activities, interests, status, status_changed_by, status_changed_at, created_at, updated_at)
SELECT mm.new_id, tpl.id, mm.phase_id, mm.activity_id, mm.role, mm.sort, mm.stakeholder_name,
       coalesce(s.contact_person, ''), coalesce(s.email, ''), coalesce(s.phone, ''),
       -- Drop the generated "Leidend bij: … / Betrokken bij: …" summary from the first import.
       CASE WHEN s.description ~ '^(Leidend bij|Betrokken bij):' THEN '' ELSE coalesce(s.description, '') END,
       s.deadline,
       -- Drop the generated per-step to-do list: it is now the activity's description and result.
       CASE WHEN s.activities ~ '^[0-9]+\\.[0-9]+ .*\\((leidend|betrokken)\\)' THEN '' ELSE coalesce(s.activities, '') END,
       coalesce(s.interests, ''), coalesce(s.status, 'not_started'), s.status_changed_by, s.status_changed_at,
       mm.created_at + mm.sort * interval '1 microsecond', now()
FROM member_map mm
CROSS JOIN tpl
LEFT JOIN stakeholders s ON s.id = mm.src_id;

INSERT INTO history_events (project_id, entity_type, entity_id, op, before, after, actor_id, batch_id, note)
${event("stakeholder", "create", "s")}
FROM stakeholders s JOIN member_map mm ON mm.new_id = s.id CROSS JOIN import_ctx c ORDER BY s.created_at;

-- 3. Documentation and comments go along with every copy
WITH ins AS (
  INSERT INTO doc_links (project_id, stakeholder_id, title, url, description, created_by, created_at, updated_at)
  SELECT l.project_id, mm.new_id, l.title, l.url, l.description, l.created_by, l.created_at, now()
  FROM member_map mm JOIN doc_links l ON l.stakeholder_id = mm.src_id AND l.deleted_at IS NULL
  RETURNING *
)
INSERT INTO history_events (project_id, entity_type, entity_id, op, before, after, actor_id, batch_id, note)
${event("doc_link", "create", "ins")}
FROM ins CROSS JOIN import_ctx c;

WITH ins AS (
  INSERT INTO doc_files (project_id, stakeholder_id, blob_id, filename, mime_type, size, created_by, created_at, updated_at)
  SELECT d.project_id, mm.new_id, d.blob_id, d.filename, d.mime_type, d.size, d.created_by, d.created_at, now()
  FROM member_map mm JOIN doc_files d ON d.stakeholder_id = mm.src_id AND d.deleted_at IS NULL
  RETURNING *
)
INSERT INTO history_events (project_id, entity_type, entity_id, op, before, after, actor_id, batch_id, note)
${event("doc_file", "create", "ins")}
FROM ins CROSS JOIN import_ctx c;

WITH ins AS (
  INSERT INTO comments (project_id, phase_id, stakeholder_id, author_id, body, labels, edited_at, created_at, updated_at)
  SELECT k.project_id, NULL, mm.new_id, k.author_id, k.body, k.labels, k.edited_at, k.created_at, now()
  FROM member_map mm JOIN comments k ON k.stakeholder_id = mm.src_id AND k.deleted_at IS NULL
  RETURNING *
)
INSERT INTO history_events (project_id, entity_type, entity_id, op, before, after, actor_id, batch_id, note)
${event("comment", "create", "ins")}
FROM ins CROSS JOIN import_ctx c;

-- 4. Soft-delete the converted phase-level rows (they can be restored via Geschiedenis)
CREATE TEMP TABLE old_rows ON COMMIT DROP AS
SELECT s.id, ${snapshot.stakeholder("s")} AS before
FROM stakeholders s
WHERE s.id IN (SELECT src_id FROM member_map WHERE src_id IS NOT NULL);

UPDATE stakeholders s
SET deleted_at = now(), version = s.version + 1, updated_at = now()
WHERE s.id IN (SELECT id FROM old_rows);

INSERT INTO history_events (project_id, entity_type, entity_id, op, before, after, actor_id, batch_id, note)
${event("stakeholder", "delete", "s", "o.before")}
FROM stakeholders s JOIN old_rows o ON o.id = s.id CROSS JOIN import_ctx c;

DO $$
DECLARE a int; s int; n int; o int;
BEGIN
  SELECT count(*) INTO a FROM act_import;
  SELECT count(*) INTO s FROM member_map;
  SELECT count(*) INTO n FROM member_map WHERE src_id IS NULL;
  SELECT count(*) INTO o FROM old_rows;
  RAISE NOTICE 'Klaar: % activiteiten, % stakeholderregels (% nieuw zonder bron), % oude regels vervangen.', a, s, n, o;
END $$;

COMMIT;
`;
  writeFileSync(output, sql, "utf8");

  console.log(`${phases.length} fases, ${activityValues.length} activiteiten, ${memberValues.length} stakeholderkoppelingen.`);
  if (missingPhases.length) console.log(`\nLET OP – fases niet gevonden in "${projectName}": ${missingPhases.join("; ")}`);
  if (newParties.length) {
    console.log(`\nPartijen zonder bestaande regel in die fase (worden leeg aangemaakt):\n  ${newParties.join("\n  ")}`);
  } else {
    console.log("Alle partijen hebben een bestaande regel om van te kopiëren.");
  }
  console.log(`\nSQL geschreven naar ${output}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
