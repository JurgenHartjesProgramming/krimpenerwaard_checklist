/**
 * Convert the "Belangenverstrengeling per fase" Excel into SQL that adds each conflict to the matching
 * ACTIVITY of a project (shown under "Belangenconflicten" on the activity page).
 *
 * Usage:
 *   npx tsx scripts/activity-conflicts-to-sql.ts "<file.xlsx>" [output.sql] [project name]
 *
 * Input: worksheet "Belangen per deelfase":
 *   A Fase | B Nr. deelfase | C Deelfase | D Conflict nr. | E Thema | F Belangenconflict | G Ernst |
 *   H Kant A | I Kant B | J Waarom botsen de belangen? | K Mogelijke oplossingsrichtingen | …
 * A row is linked to the activity with the same number ("Nr. deelfase") in the phase with the same
 * name. Per activity, conflicts are ordered by severity (Hoog, Middel, Laag) and number.
 * Conflicts an activity already has (same conflict number) are skipped, so a second run adds nothing.
 */
import { writeFileSync } from "node:fs";
import ExcelJS from "exceljs";
import { importContext, q, snapshot } from "./lib/sql";

const SEVERITY_ORDER: Record<string, number> = { hoog: 0, middel: 1, laag: 2 };

function text(v: ExcelJS.CellValue): string {
  if (v === null || v === undefined) return "";
  if (typeof v === "object") {
    if ("richText" in v) return v.richText.map((t) => t.text).join("");
    if ("text" in v && typeof v.text === "string") return v.text;
    if ("result" in v) return String(v.result ?? "");
  }
  return String(v);
}

async function main() {
  const [path, output = "imports/activiteit-belangenconflicten.sql", projectName = "Sjabloon – Stakeholders per fase"] =
    process.argv.slice(2);
  if (!path) {
    console.error('Usage: npx tsx scripts/activity-conflicts-to-sql.ts "<file.xlsx>" [output.sql] [project name]');
    process.exit(1);
  }
  const source = path.split(/[\\/]/).pop()!;
  const wb = new ExcelJS.Workbook();
  await wb.xlsx.readFile(path);
  const ws = wb.getWorksheet("Belangen per deelfase");
  if (!ws) throw new Error('Worksheet "Belangen per deelfase" not found.');

  interface Row {
    phase: string;
    stepNr: string;
    nr: number | null;
    theme: string;
    title: string;
    severity: string;
    sideA: string;
    sideB: string;
    why: string;
    solutions: string;
  }
  const rows: Row[] = [];
  ws.eachRow((row, r) => {
    if (r === 1) return;
    const c = (i: number) => text(row.getCell(i).value).trim();
    if (!c(1) || !c(6)) return;
    const nr = Number(c(4));
    rows.push({
      phase: c(1).replace(/^Fase\s+\d+\s*[–-]\s*/, "").trim(),
      stepNr: c(2),
      nr: Number.isFinite(nr) && c(4) !== "" ? nr : null,
      theme: c(5),
      title: c(6),
      severity: c(7),
      sideA: c(8).split(/\s*;\s*/).filter(Boolean).join("; "),
      sideB: c(9).split(/\s*;\s*/).filter(Boolean).join("; "),
      why: c(10),
      solutions: c(11),
    });
  });

  // Order within each activity: severity, then conflict number.
  const groups = new Map<string, Row[]>();
  for (const r of rows) {
    const key = `${r.phase}|${r.stepNr}`;
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key)!.push(r);
  }
  const values: string[] = [];
  for (const list of groups.values()) {
    list
      .sort(
        (a, b) =>
          (SEVERITY_ORDER[a.severity.toLowerCase()] ?? 9) - (SEVERITY_ORDER[b.severity.toLowerCase()] ?? 9) ||
          (a.nr ?? 0) - (b.nr ?? 0),
      )
      .forEach((r, i) => {
        values.push(
          `  (${q(r.phase)}, ${q(r.stepNr)}, ${r.nr ?? "NULL"}, ${q(r.title)}, ${q(r.theme)}, ${q(r.severity)}, ${q(r.sideA)}, ${q(r.sideB)}, ${q(r.why)}, ${q(r.solutions)}, ${i + 1})`,
        );
      });
  }

  const note = q(`Belangenconflicten per activiteit uit Excel: ${source}`);
  const sql = `-- Conflicts per activity from: ${source}
-- Generated by scripts/activity-conflicts-to-sql.ts on ${new Date().toISOString()}
-- Adds ${values.length} conflict rows to the activities of project "${projectName}".
-- Conflicts an activity already has (same number) are skipped; running this twice adds nothing.

BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM projects WHERE name = ${q(projectName)} AND deleted_at IS NULL) THEN
    RAISE EXCEPTION 'Project "%" niet gevonden. Er is niets toegevoegd.', ${q(projectName)};
  END IF;
END $$;

${importContext}

CREATE TEMP TABLE conflict_import (
  phase_name text, activity_number text, conflict_number int, title text, theme text, severity text,
  side_a text, side_b text, why text, solutions text, sort int
) ON COMMIT DROP;
INSERT INTO conflict_import VALUES
${values.join(",\n")};

WITH ins AS (
  INSERT INTO activity_conflicts (project_id, activity_id, conflict_number, title, theme, severity, side_a, side_b, why, solutions, sort_order)
  SELECT p.id, a.id, ci.conflict_number, ci.title, ci.theme, ci.severity, ci.side_a, ci.side_b, ci.why, ci.solutions, ci.sort
  FROM conflict_import ci
  JOIN projects p ON p.name = ${q(projectName)} AND p.deleted_at IS NULL
  JOIN phases f ON f.project_id = p.id AND f.name = ci.phase_name AND f.deleted_at IS NULL
  JOIN activities a ON a.phase_id = f.id AND a.number = ci.activity_number AND a.deleted_at IS NULL
  WHERE NOT EXISTS (
    SELECT 1 FROM activity_conflicts k
    WHERE k.activity_id = a.id AND k.deleted_at IS NULL
      AND (k.conflict_number = ci.conflict_number OR (ci.conflict_number IS NULL AND k.title = ci.title))
  )
  RETURNING *
)
INSERT INTO history_events (project_id, entity_type, entity_id, op, before, after, actor_id, batch_id, note)
SELECT ins.project_id, 'activity_conflict', ins.id, 'create', NULL, ${snapshot.activity_conflict("ins")},
       c.actor_id, c.batch_id, ${note}
FROM ins CROSS JOIN import_ctx c;

DO $$
DECLARE n int;
BEGIN
  SELECT count(*) INTO n FROM conflict_import ci
  WHERE NOT EXISTS (
    SELECT 1 FROM activities a
    JOIN phases f ON f.id = a.phase_id AND f.deleted_at IS NULL
    JOIN projects p ON p.id = f.project_id AND p.name = ${q(projectName)} AND p.deleted_at IS NULL
    WHERE a.number = ci.activity_number AND f.name = ci.phase_name AND a.deleted_at IS NULL
  );
  IF n > 0 THEN RAISE NOTICE '% conflictregels hadden geen bijpassende activiteit en zijn overgeslagen.', n; END IF;
END $$;

COMMIT;
`;
  writeFileSync(output, sql, "utf8");
  console.log(`${rows.length} conflictregels voor ${groups.size} activiteiten.`);
  console.log(`SQL geschreven naar ${output}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
